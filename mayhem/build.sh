#!/usr/bin/env bash
# mayhem/build.sh — build sslh's fuzz harnesses (sanitized) and the test.sh oracles (normal flags).
# Runs in /mayhem as `mayhem`; re-runnable on a built tree and offline (deps are apt -dev packages).
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"
# libproxyprotocol, prebuilt static by mayhem/Dockerfile; configure finds proxy_protocol.h through
# C_INCLUDE_PATH and turns on HAVE_PROXYPROTOCOL (as upstream's own Dockerfile does it).
LIBPP=/opt/toolchains/deps/libproxyprotocol-1.3.4
export C_INCLUDE_PATH="$LIBPP/include${C_INCLUDE_PATH:+:$C_INCLUDE_PATH}"
export LIBRARY_PATH="$LIBPP/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
OUT="$SRC/mayhem/build"          # gitignored by mayhem/.gitignore
mkdir -p "$OUT/test"

# 1) The project, upstream's way: configure (writes the gitignored Makefile/config.h) + make
#    libsslh.a with the sanitizer and DWARF-3 flags. CFLAGS goes through the environment because
#    Makefile.in appends to it (CFLAGS +=); DEBUG_FLAGS last so its -gdwarf-3 wins.
[ -f Makefile ] && [ -f config.h ] || ./configure
# -fsanitize=fuzzer-no-link: SanCov edge instrumentation on the project objects, so the fuzzer sees
# coverage in sslh code and not only in the harness.
FUZZ_CFLAGS="$SANITIZER_FLAGS -fsanitize=fuzzer-no-link $DEBUG_FLAGS"
# The same holds for sslh-conf.c, generated by conf2struct: it stores typed libconfig lookup
# helpers (myconfig_setting_lookup_stringcpy, ...) in one generic pointer type and calls them
# through it (sslh-conf.c:1750) for every setting read.
# Vendored argtable3 calls every option's reset/scan/check callback through a generic
# `void (*)(void*)` pointer (argtable3.c:5351 et al.), which UBSan's -fsanitize=function flags on
# every parse, before any input byte is read. Relax only that check, only on these two objects (built
# first so the libsslh.a make below finds it up to date). ASan and the rest of UBSan stay halting.
CFLAGS="$FUZZ_CFLAGS -fno-sanitize=function" make argtable3.o sslh-conf.o CC="$CC"
CFLAGS="$FUZZ_CFLAGS" make -j"$MAYHEM_JOBS" libsslh.a CC="$CC"

# The objects of libsslh.a minus sslh-main.o (it holds main() and the daemon start-up).
LIBOBJS="sslh-conf.o common.o log.o probe.o tls.o argtable3.o collection.o gap.o tcp-probe.o landlock.o proxyprotocol.o"
LIBS="-lpcre2-8 -lconfig -lproxyprotocol -lm"
DEFS="-DENABLE_REGEX -DLIBCONFIG -DLIBPCRE"

$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.c -o "$OUT/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OUT/standalone_main.o"

# 2a) fuzz_probe (libFuzzer): fuzzer binary + run-once standalone reproducer.
for h in fuzz_probe; do
  $CC $FUZZ_CFLAGS $DEFS -I"$SRC" -c "mayhem/harnesses/$h.c" -o "$OUT/$h.o"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$OUT/$h.o" $LIBOBJS "$OUT/lsan_off.o" $LIBS -o "$OUT/$h"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS "$OUT/standalone_main.o" "$OUT/$h.o" $LIBOBJS "$OUT/lsan_off.o" $LIBS -o "$OUT/$h-standalone"
done

# 2b) fuzz_config (AFL, one input per process — see the harness for why): the config reader's
#     sources compiled with afl-clang-fast and the same sanitizer/DWARF flags, into their own
#     directory so they don't clash with the libFuzzer objects. No -standalone: an AFL target is
#     its own reproducer. -fno-sanitize=function for the reason given in step 1.
A="$OUT/afl"; mkdir -p "$A"
AFL_FLAGS="$SANITIZER_FLAGS -fno-sanitize=function $DEBUG_FLAGS $DEFS -I$SRC"
for src in sslh-conf.c argtable3.c mayhem/harnesses/fuzz_config.c mayhem/lsan_off.c; do
  afl-clang-fast $AFL_FLAGS -c "$src" -o "$A/$(basename "${src%.c}").o"
done
afl-clang-fast $AFL_FLAGS "$A/fuzz_config.o" "$A/sslh-conf.o" "$A/argtable3.o" "$A/lsan_off.o" $LIBS -o "$OUT/fuzz_config"

# 3) The test oracles, with normal flags (no sanitizers), in their own directory:
#    upstream's hash and gap unit drivers (hashtest/, testgap/, golden .ref outputs), and the
#    probe known-answer driver over the same protocol list as fuzz_probe.
T="$OUT/test"
# htest.c calls hash_item_print()/hash_dump() that hash.h only declares under gcc-style implicit
# declarations; clang 19 makes that an error by default, so relax just that diagnostic.
$CC -O2 $COVERAGE_FLAGS -Wno-error=implicit-function-declaration -DHASH_DEBUG -o "$T/htest" hashtest/htest.c hash.c gap.c
$CC -O2 $COVERAGE_FLAGS -DHASH_TESTING -o "$T/gtest" testgap/gtest.c gap.c
$CC -O2 $COVERAGE_FLAGS $DEFS -I"$SRC" -o "$T/probe_kat" mayhem/harnesses/probe_kat.c \
    probe.c tls.c log.c common.c sslh-conf.c argtable3.c collection.c gap.c tcp-probe.c landlock.c proxyprotocol.c $LIBS
$CC -O2 $COVERAGE_FLAGS $DEFS -I"$SRC" -o "$T/config_dump" mayhem/harnesses/config_dump.c \
    sslh-conf.c argtable3.c $LIBS
# The daemons and echosrv for upstream's end-to-end suite t/run, from the same sources and link
# lines as Makefile.in's sslh-fork/sslh-select/sslh-ev/echosrv targets, but compiled straight into
# $T so they don't share (sanitized) objects with libsslh.a above.
SSLH_SRCS="sslh-conf.c common.c log.c sslh-main.c probe.c tls.c argtable3.c collection.c gap.c tcp-probe.c landlock.c proxyprotocol.c"
LOOP_SRCS="processes.c udp-listener.c hash.c tcp-listener.c"
$CC -O2 $COVERAGE_FLAGS $DEFS -I"$SRC" -o "$T/sslh-fork" sslh-fork.c $SSLH_SRCS $LIBS
$CC -O2 $COVERAGE_FLAGS $DEFS -I"$SRC" -o "$T/sslh-select" sslh-select.c $LOOP_SRCS $SSLH_SRCS $LIBS
$CC -O2 $COVERAGE_FLAGS $DEFS -I"$SRC" -o "$T/sslh-ev" sslh-ev.c $LOOP_SRCS $SSLH_SRCS $LIBS -lev
$CC -O2 $COVERAGE_FLAGS $DEFS -I"$SRC" -o "$T/echosrv" echosrv.c echosrv-conf.c argtable3.c $LIBS
echo "build.sh: OK"
